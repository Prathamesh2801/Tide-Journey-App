/**
 * Writes dist/sw-manifest.js - the precache list the service worker reads.
 *
 * Generated from the shared keep-list so it always matches exactly what
 * the build ships. The version is a hash of that list, so a redeploy with
 * different media invalidates the old cache automatically while an
 * unchanged redeploy leaves the tablets' cache intact.
 */
import { createHash } from 'node:crypto'
import { stat, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { buildKeepList, ROOT } from './media-keep-list.mjs'

const DIST = join(ROOT, 'dist')

const keep = [...(await buildKeepList())].sort()
// Paths are relative to the deploy folder, matching how the app requests
// them, so the worker's cache keys line up with real fetches.
const files = keep.map((path) => `./media/${path}`)

let bytes = 0
for (const path of keep) {
  try {
    bytes += (await stat(join(DIST, 'media', path))).size
  } catch {
    // Pruned or not yet built - the worker tolerates a miss at runtime.
  }
}

const version = createHash('sha1').update(files.join('\n')).digest('hex').slice(0, 12)

await writeFile(
  join(DIST, 'sw-manifest.js'),
  `// Generated by scripts/build-sw-manifest.mjs - do not edit.\n` +
    `self.__MEDIA_MANIFEST = ${JSON.stringify({ version, bytes, files }, null, 2)};\n`,
  'utf8'
)

console.log(
  `sw-manifest.js: ${files.length} files, ${(bytes / 1048576).toFixed(1)} MB, version ${version}`
)
