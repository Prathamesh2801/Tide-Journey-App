/**
 * Writes dist/sw-manifest.js - the precache list the service worker reads.
 *
 * Generated from the shared keep-list so it always matches exactly what
 * the build ships. The version is a hash of that list, so a redeploy with
 * different media invalidates the old cache automatically while an
 * unchanged redeploy leaves the tablets' cache intact.
 */
import { createHash } from 'node:crypto'
import { readdir, stat, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { buildKeepList, ROOT } from './media-keep-list.mjs'

const DIST = join(ROOT, 'dist')

/**
 * The built JS/CSS/font/art files.
 *
 * These have to be precached, not just cached on demand. Route chunks are
 * lazy-loaded, so an experience nobody has opened yet has never fetched
 * its chunk - and a tablet that holds every megabyte of media would still
 * fail to open that experience with a blank screen if the laptop is
 * briefly unreachable. Measured: "Failed to fetch dynamically imported
 * module". It is under a megabyte in total, so there is no reason to be
 * clever about which ones.
 */
async function shellFiles() {
  const out = ['./', './index.html']
  try {
    for (const name of await readdir(join(DIST, 'assets'))) {
      out.push(`./assets/${name}`)
    }
  } catch {
    // No assets folder - nothing to add.
  }
  return out
}

const keep = [...(await buildKeepList())].sort()
// Paths are relative to the deploy folder, matching how the app requests
// them, so the worker's cache keys line up with real fetches.
const files = keep.map((path) => `./media/${path}`)

let bytes = 0
for (const path of keep) {
  try {
    bytes += (await stat(join(DIST, 'media', path))).size
  } catch {
    // Pruned or not yet built - the worker tolerates a miss at runtime.
  }
}

const shell = await shellFiles()

// The version covers the shell too: asset filenames are content-hashed, so
// a code change alters this list and correctly invalidates the old cache,
// while a rebuild with no changes leaves the tablets' cache untouched.
const version = createHash('sha1')
  .update([...files, ...shell].join('\n'))
  .digest('hex')
  .slice(0, 12)

await writeFile(
  join(DIST, 'sw-manifest.js'),
  `// Generated by scripts/build-sw-manifest.mjs - do not edit.\n` +
    `self.__MEDIA_MANIFEST = ${JSON.stringify({ version, bytes, files, shell }, null, 2)};\n`,
  'utf8'
)

console.log(
  `sw-manifest.js: ${files.length} media + ${shell.length} shell files, ` +
    `${(bytes / 1048576).toFixed(1)} MB, version ${version}`
)
